#!/usr/bin/env node
// Regenerates rules.json + lists.js from ../security/trackers.js. Run after editing the tracker list,
// then press the reload arrow for "Tracker Cleaner" in chrome://extensions.
const fs = require('fs'), path = require('path');
const T = require('../security/trackers.js');
const rules = [{ id: 1, priority: 1, action: { type: 'block' },
  condition: { requestDomains: T.DOMAINS, resourceTypes: ['script', 'xmlhttprequest', 'image', 'ping', 'sub_frame', 'media', 'other', 'websocket', 'font', 'stylesheet'] } },
  // ad / telemetry paths on the sites' own domains (YouTube, Google)
  ...T.AD_PATHS.map((f, i) => ({ id: 100 + i, priority: 1, action: { type: 'block' }, condition: { urlFilter: f, resourceTypes: ['script', 'xmlhttprequest', 'image', 'ping', 'sub_frame', 'media', 'other'] } }))];
fs.writeFileSync(path.join(__dirname, 'rules.json'), JSON.stringify(rules, null, 1) + '\n');
fs.writeFileSync(path.join(__dirname, 'lists.js'), `// Generated by build.js from security/trackers.js. Do not edit.
const DOMAINS = ${JSON.stringify(T.DOMAINS)};
const COOKIE_RE = ${T.COOKIE_RE};
const KEEP_RE = ${T.KEEP_RE};
`);
console.log(`rules.json: ${T.DOMAINS.length} blocked domains + ${T.AD_PATHS.length} ad paths; lists.js written`);
