#!/usr/bin/env node
// Regenerates rules.json + rules-google.json + rules-params.json + lists.js from ../security/trackers.js. Run after editing the tracker list,
// then press the reload arrow for "Tracker Cleaner" in chrome://extensions.
const fs = require('fs'), path = require('path');
const T = require('../security/trackers.js'), { SIGNIN_HOSTS } = require('./guard.js');
// rules.json = ruleset "trackers" (C01); rules-google.json = ruleset "google-paths" (C02)
// Two rules. A whole site (two labels: segment.com, mixpanel.com) is blocked from other sites only (thirdParty), because
// some are also products people use. An entry with more labels is a tracking subdomain of a larger site
// (adservice.google.com, bat.bing.com): to google.com or bing.com it is first-party, so it is blocked everywhere.
const TYPES = ['script', 'xmlhttprequest', 'image', 'ping', 'sub_frame', 'media', 'other', 'websocket', 'font', 'stylesheet'];
const sub = (d) => d.split('.').length > 2;
const rules = [{ id: 1, priority: 1, action: { type: 'block' }, condition: { requestDomains: T.DOMAINS.filter((d) => !sub(d)), domainType: 'thirdParty', resourceTypes: TYPES } },
  { id: 2, priority: 1, action: { type: 'block' }, condition: { requestDomains: T.DOMAINS.filter(sub), resourceTypes: TYPES } }];
// rules-params.json = ruleset "url-params" (C23): tracking parameters are taken off the URL of a page being opened,
// except on the sign-in hosts (guard.js)
const params = [{ id: 1, priority: 1, action: { type: 'redirect', redirect: { transform: { queryTransform: { removeParams: T.URL_PARAMS } } } },
  condition: { resourceTypes: ['main_frame'], excludedRequestDomains: SIGNIN_HOSTS } }];
// ad / telemetry paths on the sites' own domains (YouTube, Google); never on the sign-in hosts, as page or as request
const SIGNIN = ['accounts.google.com', 'accounts.youtube.com'];
const google = T.AD_PATHS.map((f, i) => ({ id: 100 + i, priority: 1, action: { type: 'block' }, condition: { urlFilter: f,
  resourceTypes: ['script', 'xmlhttprequest', 'image', 'ping', 'sub_frame', 'media', 'other'], excludedInitiatorDomains: SIGNIN, excludedRequestDomains: SIGNIN } }));
fs.writeFileSync(path.join(__dirname, 'rules.json'), JSON.stringify(rules, null, 1) + '\n');
fs.writeFileSync(path.join(__dirname, 'rules-google.json'), JSON.stringify(google, null, 1) + '\n');
fs.writeFileSync(path.join(__dirname, 'rules-params.json'), JSON.stringify(params, null, 1) + '\n');
fs.writeFileSync(path.join(__dirname, 'lists.js'), `// Generated by build.js from security/trackers.js. Do not edit.
const DOMAINS = ${JSON.stringify(T.DOMAINS)};
const COOKIE_RE = ${T.COOKIE_RE};
const GOOGLE_RE = ${T.GOOGLE_RE};
const KEEP_RE = ${T.KEEP_RE};
const URL_PARAMS = ${JSON.stringify(T.URL_PARAMS)};
// load-balancer and bot-protection cookies: no evidence of tracking (security/trackers.js says why)
const INFRA_COOKIE_RE = ${T.INFRA_COOKIE_RE};
if (typeof module !== 'undefined') module.exports = { DOMAINS, COOKIE_RE, GOOGLE_RE, KEEP_RE, URL_PARAMS, INFRA_COOKIE_RE };
`);
console.log(`rules.json: ${T.DOMAINS.length} blocked domains + ${T.AD_PATHS.length} ad paths (rules-google.json) + ${T.URL_PARAMS.length} URL parameters (rules-params.json); lists.js written`);
