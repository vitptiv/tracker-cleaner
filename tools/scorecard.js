#!/usr/bin/env node
'use strict';
// Writes docs/scorecard.md from what the lab trips measured: lab/misses.json (node test/lab/trip-cleaner.js) and
// lab/ff2-misses.json (node test/lab/ff2-trip.js). Run it after both trips:  node tools/scorecard.js
const fs = require('node:fs'), path = require('node:path');
const root = path.join(__dirname, '..'), read = (f) => JSON.parse(fs.readFileSync(path.join(root, f), 'utf8'));

// the short name of each way, in the words of the README
const NAMES = {
  T1: 'Browser cookie', T2: 'Sign-in cookie seen on other sites', T3: 'Tracking-kit cookie per site', T4: 'Click-ID cookie',
  T5: 'Redirector cookie', T6: 'Matched pair of IDs between two companies', T7: 'Disguised subdomain', T8: 'Like-button frame cookie',
  T9: 'ID in local storage', T10: 'Tab journey in session storage', T11: 'ID in IndexedDB', T12: 'ID in cache storage',
  T13: 'Service worker holding the ID', T14: 'Storage totals', T15: 'Saved script with an ID', T16: 'Cache tag on an image',
  T17: 'Compiled copy of the kit', T18: 'Saved site icons', T19: 'History and visited links', T20: 'Remembered servers',
  T21: 'Forced-HTTPS list', T22: 'Notification permission', T23: 'Page address and referrer', T24: 'IP address, browser, language',
  T25: 'Computed fingerprint', T26: 'Events with values', T27: 'Hashed e-mail', T28: 'Page-close beacon', T29: 'Outgoing-click ping',
  T30: 'Redirect log', T31: "Like and share on the test network's own page", T32: '"Sign in with Testbook"',
  T33: "Purchase reported by the shop's server", T34: 'Push subscription', T35: 'Typing and mouse rhythm', T36: 'Probe of programs on your computer',
  F1: "Site's own ID cookie", F2: 'ID kept without a cookie, sent to the collector', F3: 'ID carried in the link between sites',
  F4: 'Scripted hand-off between sites', F5: "Click record on the site's own server", F6: 'Fingerprint used to join sites',
  F7: 'Cookie set during a sign-in', F8: 'Page address and referrer', F9: 'Probe of programs on your computer', F10: 'Cache tag on an image',
};
const FOLLOWS = '**still follows you**';

function scorecard(misses, ff2) {
  if (misses.extension !== ff2.extension) throw new Error(`the two trips measured different versions: ${misses.extension} and ${ff2.extension}`);
  // one cell of the lab's table: what a run says of a way at the end
  const cell = (run, id) => { const r = run.rows[id], c = run.counts;
    if (!r || r.status === 'not built') return 'not built';
    if (String(r.status).startsWith('kept on purpose')) return 'kept on purpose';
    if (r.atEnd && !(c.simulated || []).includes(id)) return FOLLOWS;
    return r.status === 'unlinked' ? 'arrives, not tied to you' : 'stopped'; };
  const strong = misses.runs.A, yes = misses.runs.Q, ids = Object.keys(NAMES).filter((id) => id.startsWith('T'));
  const rows = ids.map((id) => [id, NAMES[id], cell(strong, id), cell(yes, id)]);
  for (const [run, col] of [[strong, 2], [yes, 3]]) {
    const n = rows.filter((r) => r[col] === FOLLOWS).length;
    if (n !== run.counts.atEnd) throw new Error(`${n} rows still follow, but the trip counted ${run.counts.atEnd}`); }
  // the hidden collector: measured with everything on; it raises no question, so a yes changes nothing
  if (ff2.questionsRaised) throw new Error('the hidden-collector trip raised questions: the yes column needs its own run');
  for (const f of ff2.rows) { const v = f.stoppedGoingForward ? 'stopped' : FOLLOWS; rows.push(['H' + f.id.slice(1), NAMES[f.id], v, v]); }
  const built = ids.length - ids.filter((id) => cell(strong, id) === 'not built').length;
  return ['# Scorecard', '', '<!-- generated by tools/scorecard.js from lab/misses.json and lab/ff2-misses.json; do not edit by hand -->', '',
    `Measured with version ${misses.extension} in a real Chrome against the local test lab in \`lab/\`: ${ids.length} ways a pretend social`
      + ` network follows a visitor (T), and ${ff2.of} ways of a hidden collector behind each site's own address (H).`,
    `Still following you at the end, at Strongest with no press: ${strong.counts.atEnd} of the ${built} T ways built and ${ff2.survives} of`
      + ` ${ff2.of} H; with every question answered yes: ${yes.counts.atEnd} and ${ff2.survives}.`,
    'The H ways are stopped from the moment the cleaner has seen the same code on two sites; the first contact always gets through.', '',
    '| # | Way of following you | Strongest, no press | Every question answered yes |', '|---|---|---|---|',
    ...rows.map((r) => `| ${r.join(' | ')} |`), ''].join('\n');
}
module.exports = { scorecard };
if (require.main === module) {
  fs.writeFileSync(path.join(root, 'docs', 'scorecard.md'), scorecard(read('lab/misses.json'), read('lab/ff2-misses.json')));
  console.log('written: docs/scorecard.md');
}
